package kz.mybrain.superkassa.desktop.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Размеры элементов.
 *
 * Ширины полей заданы по смыслу вводимого, а не числом на месте: «сумма»
 * везде одной ширины, и колонки экранов сходятся сами собой.
 */
object Sizes {
    /** Количество товара — две-три цифры. */
    val fieldQuantity = 140.dp

    /** Цена позиции. */
    val fieldPrice = 180.dp

    /** Пин и короткий код. */
    val fieldPin = 160.dp

    /** Сумма денег и выбор роли. */
    val fieldAmount = 200.dp

    /** Вид оплаты и реквизиты кассы. */
    val fieldChoice = 220.dp

    /** Строка раскрытого списка выбора: по Material 3 у пункта меню 48 точек. */
    val pickerRow: Dp = 48.dp

    /**
     * Высота раскрытого списка выбора.
     *
     * Список раскрывается поверх формы, и предел ему нужен не ради вида:
     * внутри он прокручивается сам, и строки собираются по мере показа.
     * В кабинете сети торговых точек и касс — по две тысячи.
     */
    val pickerList: Dp = 336.dp

    /**
     * Высота перечня акцизных марок в окне.
     *
     * Марок бывает по числу единиц товара; перечень выше этого начинает
     * распирать окно, и кнопка уходит за нижний край.
     */
    val stampList: Dp = 220.dp

    /**
     * Высота перечня сведений в окне подробностей строки чека.
     *
     * Строк у позиции с марками, кодами и скидкой больше десяти; выше
     * этого перечень прокручивается, а кнопка закрытия остаётся на месте.
     */
    val detailList: Dp = 480.dp

    /** Поля отраслевых реквизитов, скидка и наценка на чек. */
    val fieldForm = 240.dp

    /** Штрихкод. */
    val fieldBarcode = 320.dp

    /**
     * Название кассы со значком объяснения.
     *
     * Подпись «Своё название кассы» вместе со значком в поле формы
     * не помещалась и переносилась на вторую строку, поле вырастало
     * и уезжало от кнопок рядом.
     */
    val fieldName = 320.dp

    /** Столбец ответа источника в сверке состояний: «Да», «Нет», «Не знает». */
    val stateColumn = 120.dp

    /** Поле короткого кода: ОКЭД, КАТО. */
    val fieldCode = 160.dp

    /**
     * Сколько ширины поля занимает не текст: рамка, отступы и значок списка.
     *
     * По этой величине считается, сколько букв поместится в строку выбора:
     * длинное название иначе переносится на вторую строку и обрезается рамкой.
     */
    val fieldTextInset = 64.dp

    /** Скругления шкалы форм Material 3. */
    val smallCorner = 8.dp
    val corner = 12.dp
    val largeCorner = 16.dp
    val hugeCorner = 28.dp

    /** Скругление плашки состояния. */
    val chipCorner = 6.dp

    /**
     * Значок внутри плашки: стрелка выпадающего списка у отбора.
     *
     * Мельче строчного значка: в полный рост он распирал плашку отбора,
     * и та вставала выше соседних в ряду.
     */
    val chipIcon: Dp = 18.dp

    /** Подъём диалога над содержимым. */
    val dialogElevation = 6.dp

    /** Колонка экрана входа: список касс и пин. */
    val loginColumn = 760.dp

    /** Значок пустого состояния. */
    val emptyIcon = 48.dp

    /**
     * Значок пустого состояния в плотном списке.
     *
     * Мельче общего: журнал идёт строками без воздуха, и значок в полный
     * рост заслонял бы строку под ним.
     */
    val emptyIconDense = 40.dp

    /**
     * Запас сегмента переключателя поверх самой длинной подписи: поля
     * кнопки и галочка выбранного значения.
     *
     * Ширина у всех сегментов одинаковая: подпись «Сатып алу» длиннее
     * «Сату» вдвое, и по содержимому кнопки вышли бы разного размера.
     */
    val segmentInset = 56.dp

    /** Толщина полосы прокрутки. */
    val scrollbar = 8.dp

    /** Высота полоски ожидания под шапкой: место под неё есть всегда. */
    val busyLine = 4.dp

    /**
     * Рост поля ввода и кнопки, стоящей с ним в одной строке.
     *
     * У `OutlinedTextField` Material 3 это 56 dp. Кнопка рядом ниже поля
     * на десять пикселей выглядит съехавшей, поэтому рост берётся отсюда
     * обеими, а не подбирается на месте.
     */
    val fieldHeight = 56.dp

    /** Наименьшая ширина рельса разделов — по Material 3. */
    val rail = 80.dp

    /**
     * Колонка списка касс в кабинете: название кассы с номером КГД
     * и торговой точкой под ним, а справа — плашка состояния.
     *
     * Прежде она брала ширину поля ввода — совпали числом случайно, —
     * и на неё не помещалось название точки: строка обрывалась
     * на «Точка…», а между карточкой и разделителем оставалась полоса
     * пустоты в две ширины поля прокрутки.
     */
    val registerColumn = 420.dp

    /**
     * Окно карты: столько, чтобы вокруг выбранной точки была видна улица
     * с соседними домами, и не столько, чтобы окно вылезло за рабочее
     * место на ноутбуке.
     */
    val mapWidth = 720.dp

    val mapHeight = 460.dp

    /**
     * Высота окна карты целиком: шапка, подсказка, карта и подвал.
     *
     * Задана, а не собрана по содержимому: карта тянется в остаток,
     * и без заданной высоты она распирала окно, выдавливая шапку
     * с подсказкой за верхний край.
     */
    val mapDialogHeight = 620.dp

    /**
     * Окно заполнения формы.
     *
     * Шире поля ввода и уже карты: в форме три-пять строк, и растянутое
     * на всю ширину окно оставляет поля висеть в пустоте.
     */
    val formDialog = 520.dp

    /** Знак выбранной точки на карте и его обводка. */
    val mapMarker = 7.dp
    val mapMarkerEdge = 3.dp

    /** Знак своего места и его ореол. */
    val mapLocation = 6.dp
    val mapHalo = 22.dp

    /**
     * Ярлычок места на карте аналитики.
     *
     * Наименьший рост и он же поперечник у одиночного: ярлычок с числом
     * тянется по надписи сам. Меньше — и в него не попасть мышью,
     * а число касс в нём не прочитать.
     */
    val mapMark = 28.dp

    /**
     * Ступени поперечника ярлычка по числу касс в нём.
     *
     * На карте страны в одном кружке сходятся то три кассы, то триста,
     * и одинаковые кружки сообщают владельцу, будто сеть разложена ровно.
     * Ступени, а не рост от числа: непрерывный размер читается как шум,
     * а три ступени различимы с одного взгляда.
     */
    val mapMarkFew = 34.dp
    val mapMarkMany = 42.dp
    val mapMarkCrowd = 52.dp

    /** Обводка ярлычка: ею он и покрашен по состоянию места. */
    val mapMarkEdge = 2.dp

    /** Обводка выбранного ярлычка: толще соседской, и он виден среди сотни. */
    val mapMarkEdgeChosen = 4.dp

    /** Тень ярлычка: по ней видно, что он лежит поверх карты, а не в ней. */
    val mapMarkLift = 3.dp

    /** Подъём выбранного ярлычка: он лежит поверх соседей и тенью это говорит. */
    val mapMarkLiftChosen = 10.dp

    /** Кружок цвета в легенде карты: тот же знак, что ярлычок, но без числа. */
    val mapLegendDot = 12.dp

    /** Карточка в углу карты: уже карты и шире самой длинной своей строки. */
    val mapNoteWidth = 280.dp

    /**
     * Список касс одного места под картой.
     *
     * Ограничен, а не по содержимому: место с десятком касс выдавливало бы
     * карту за верхний край, а карта — то, ради чего экран открыт.
     */
    val spotList = 200.dp

    /**
     * Окно аналитики одной кассы.
     *
     * Шире карты: внутри те же плитки, графики и таблицы, что и в сводке
     * по всей сети, и на ширине карты таблица переносила бы каждую строку.
     */
    val kkmSalesWidth = 900.dp

    val kkmSalesHeight = 680.dp

    /**
     * Колонка касс без положения рядом с картой.
     *
     * Уже колонки списка касс кабинета: здесь строка короче — название
     * кассы и причина под ним, — а карте нужна вся оставшаяся ширина.
     */
    val unplacedColumn = 320.dp

    /**
     * Карточка выбранной на карте кассы под картой.
     *
     * Задана, а не собрана по содержимому: у касс разное число строк —
     * у одной есть смена и номер КГД, у другой ни того ни другого, —
     * и карта прыгала бы по высоте при каждом выборе точки.
     */
    val pinCardHeight = 180.dp

    /**
     * Перечень отклонённых БФД документов на главном экране.
     *
     * Задан, а не собран по содержимому: отказы приходят пачкой — за
     * сорванную автономную работу БФД отвергает всю досылку, — и карточка
     * росла вниз, пока не выдавливала за нижний край окна и заголовок
     * «Документы смены», и сам список.
     */
    val refusedList = 200.dp

    /** Столбцы строки адреса обмена: сам адрес и время. */
    val exchangeAddressColumn = 180.dp
    val exchangeMomentColumn = 200.dp

    /**
     * Столбчатый график торговой сводки: выручка по дням и нагрузка по часам.
     *
     * Высота задана, а не собрана по содержимому: своего содержимого,
     * кроме столбиков, у графика нет, и без заданной высоты он схлопнулся
     * бы в ноль. Столько, чтобы разница между соседними днями читалась,
     * и не столько, чтобы один график занял собой весь экран.
     */
    val chartHeight = 180.dp

    /** Просвет между столбиками: тридцать дней подряд иначе сливаются в заливку. */
    val chartBarGap = 3.dp

    /** Толщина оси под столбиками: она отделяет график от подписей, а не украшает. */
    val chartAxis = 1.dp

    /** Полоса долей видов расчётов и цветной образец в её подписи. */
    val shareBar = 20.dp
    val shareSwatch = 12.dp

    /**
     * Наименьшая ширина плитки главного числа сводки.
     *
     * Шире плитки счётчика: здесь стоит не число касс, а сумма с разрядами
     * и знаком тенге, набранная крупной шкалой, — «1 284 560,00 ₸».
     */
    val salesTile = 210.dp

    /** Столбцы таблиц сводки: название кассы или точки и число под подписью. */
    val salesNameColumn = 260.dp
    val salesNumberColumn = 130.dp

    /**
     * Столбец доли сети: полоска доли и процент рядом с ней.
     *
     * Шире числового: в нём стоят два элемента, и полоске нужна длина,
     * на которой десятая часть видна десятой частью.
     */
    val salesShareColumn = 180.dp

    /** Значок в шапке раздела: крупнее строчного, мельче пустого состояния. */
    val headerIcon = 40.dp

    /** Наименьшая ширина плитки счётчика: по ней ряд итогов решает, переноситься ли. */
    val counterTile = 140.dp

    /** Значок объяснения рядом с заголовком раздела. */
    val infoIcon = 18.dp

    /**
     * Кружок тона в карточке оформления.
     *
     * Крупнее значка: это цель нажатия, а не знак, и по кружку должно
     * быть видно сам цвет, а не намёк на него.
     */
    val accentSwatch = 40.dp

    /**
     * Шаг прокрутки с клавиатуры: строка.
     *
     * Ею меряются и стрелки, и страница: страница на строку короче видимой
     * части, чтобы после прыжка на экране оставалось начало прежнего вида.
     * Примерно рост строки списка — меньший шаг заставляет стучать
     * по стрелке, больший перескакивает карточку целиком.
     */
    val scrollLine = 56.dp

    /** Кружок ожидания внутри кнопки. */
    val busyCircle = 18.dp

    /**
     * Кружок ожидания на месте содержимого.
     *
     * Крупнее кнопочного и вровень со значком пустого состояния: ожидание
     * и пустота сменяют друг друга в одном месте, и разный рост заставлял
     * бы область дёргаться в тот миг, когда пришёл ответ.
     */
    val waitCircle = 48.dp

    /** То же в плотной области: внутри карточки или строки списка. */
    val waitCircleDense = 40.dp

    /** Подъём закреплённой полосы действия над прокручиваемым списком. */
    val barElevation = 3.dp

    /** Стартовый размер окна кассы. */
    val windowWidth = 1180.dp
    val windowHeight = 820.dp

    /**
     * Меньше этого окно перестаёт быть рабочим местом.
     *
     * Ширина держит колонку кассы рядом с содержимым: у́же неё двухколонные
     * разделы — дерево точек и паспорт кассы, корзина и итоги — складываются
     * друг на друга и перестают читаться. Высота оставляет место шапке,
     * содержимому и строке действий под ним.
     */
    val windowMinWidth = 960.dp
    val windowMinHeight = 640.dp

    /**
     * Окно журнала.
     *
     * Шире главного не бывает намеренно: журнал стоит рядом с кассой
     * на том же экране, и строка обмена с путём и кодом ответа
     * помещается в эту ширину целиком.
     */
    val logWindowWidth = 920.dp
    val logWindowHeight = 640.dp

    /** Строка поиска по журналу: путь запроса или код отказа. */
    val fieldSearch = 280.dp

    /**
     * Столбцы строки журнала: уровень и источник.
     *
     * Ширина задана, а не собрана по содержимому: «Предупреждения» длиннее
     * «Отказов» вдвое, и текст записи ехал бы вправо-влево от строки
     * к строке — читать столбец сверху вниз становится нельзя.
     */
    val logLevelColumn = 130.dp
    val logSourceColumn = 100.dp
}
