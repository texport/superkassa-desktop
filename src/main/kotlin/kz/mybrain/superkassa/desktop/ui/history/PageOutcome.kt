package kz.mybrain.superkassa.desktop.ui.history

/**
 * Чем кончилось чтение страницы списка у узла.
 *
 * Прежде чтение отвечало одним `Boolean` — «есть ли за страницей ещё», —
 * и тем же `false` отвечало на молчание узла. Экран, получив `false`,
 * писал «документов нет»: кассир при покупателе с чеком в руках читал
 * отказ узла как утверждение о том, что чека не было.
 *
 * Поэтому сведений два и они разведены: прочитали ли вообще и есть ли
 * за прочитанным ещё. Первое решает, что стоит на экране; второе —
 * показывать ли кнопку подгрузки.
 */
data class PageOutcome(

    /** Узел ответил по существу: прочитанному можно верить. */
    val read: Boolean,

    /** Страница пришла полной — значит список читается дальше. */
    val more: Boolean
) {
    companion object {

        /**
         * Прочитать не удалось.
         *
         * Сюда же попадает невыбранная касса: спрашивать некого, и «за этот
         * день документов нет» было бы утверждением о кассе, которую никто
         * не назвал.
         */
        val unread = PageOutcome(read = false, more = false)

        /** Страница прочитана; [more] — пришла ли она целиком. */
        fun page(more: Boolean) = PageOutcome(read = true, more = more)
    }
}
