package kz.mybrain.superkassa.desktop.ui.map

import kz.mybrain.superkassa.desktop.server.cabinet.AddressSuggestion

/**
 * Сведение названий карты с названиями регистра.
 *
 * Одно и то же место они называют по-разному: карта пишет «проспект
 * Достык», регистр — «Достык» или «Достык даңғылы»; карта «Алматинская
 * область», регистр «Алматы облысы». Различаются приписки о виде объекта
 * и написание, а собственное имя — то же, и сводятся записи по нему.
 *
 * Выбор владельца это не отменяет: сведение только отыскивает записи
 * регистра, а адресом точки становится та, которую владелец нажал.
 */

/**
 * Слова о виде объекта: они у карты и у регистра свои.
 *
 * Список нарочно короткий: сюда попадает то, что действительно приходит
 * от службы и от регистра. Слово, которое может быть собственным именем
 * улицы, здесь не место — «Мира» или «Абая» отбросить нельзя.
 */
private val KINDS = setOf(
    "проспект", "пр", "просп", "улица", "ул", "переулок", "пер", "шоссе", "микрорайон", "мкр",
    "бульвар", "площадь", "тупик", "проезд", "даңғылы", "даңғыл", "көшесі", "көше", "ықшам",
    "шағын", "аудан", "ауданы", "район", "область", "обл", "облысы", "город", "г", "қаласы",
    "қала", "село", "с", "поселок", "пос", "ауыл", "кент", "имени", "им", "street", "avenue", "district"
)

/** Всё, что не буква и не цифра, названия не различает: «10/1» и «10 1» — один дом. */
private val PLAIN = Regex("[^\\p{L}\\p{Nd}]+")

/**
 * Название, приведённое к сравнимому виду.
 *
 * Регистр и служба расходятся в регистре букв, в «ё» и в знаках между
 * словами; сравнение по ним промахивалось бы на каждом втором адресе.
 */
internal fun addressKey(name: String): String =
    name.lowercase().replace('ё', 'е').replace(PLAIN, " ").trim()

/** То же название без слов о виде объекта: «проспект Достык» и «Достык даңғылы» сходятся. */
internal fun addressCore(name: String): String =
    addressKey(name).split(' ').filter { it.isNotBlank() && it !in KINDS }.joinToString(" ")

/**
 * Чем спрашивать регистр.
 *
 * Регистр ищет по вхождению, и «проспект Достык» в нём не находится:
 * у него записано «Достык даңғылы». Поэтому в запрос уходит собственное
 * имя без приписок — и в исходном написании, а не приведённое к нижнему
 * регистру: как регистр относится к регистру букв, приложению неизвестно.
 */
internal fun addressNeedle(name: String): String =
    name.split(PLAIN)
        .filter { it.isNotBlank() && addressKey(it) !in KINDS }
        .joinToString(" ")
        .ifBlank { name.trim() }

/**
 * Запись регистра, отвечающая названию с карты.
 *
 * Сначала полное совпадение, затем по собственному имени, затем по его
 * вхождению: у регистра к имени приписан вид объекта, у карты — свой.
 * Ничего не подошло — `null`: выдумывать запись регистра нельзя, лучше
 * сказать владельцу, что подбор не удался.
 */
internal fun matchSuggestion(items: List<AddressSuggestion>, wanted: String): AddressSuggestion? {
    if (wanted.isBlank()) return null
    val key = addressKey(wanted)
    val core = addressCore(wanted)
    return items.firstOrNull { addressKey(it.name) == key }
        ?: items.firstOrNull { core.isNotBlank() && addressCore(it.name) == core }
        ?: items.firstOrNull { core.isNotBlank() && addressCore(it.name).contains(core) }
}

/**
 * Дома регистра с тем же номером, что под меткой.
 *
 * Возвращаются все: на один номер регистр отдаёт по две записи с разными
 * кодами РКА, и какая из них дом владельца, знает только он сам. Отбор
 * по точному номеру нужен потому, что регистр ищет по вхождению
 * и на «10» отдаёт заодно «101» и «110».
 */
internal fun matchHouses(items: List<AddressSuggestion>, number: String): List<AddressSuggestion> {
    if (number.isBlank()) return emptyList()
    val key = addressKey(number)
    return items.filter { addressKey(it.name) == key }
}
