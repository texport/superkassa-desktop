package kz.mybrain.superkassa.desktop.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Раскладка журнала документов, прошлых смен и очереди.
 *
 * Общие приёмы — в [TableColumns] и [ContentWidths]; здесь только то,
 * чего у них нет и что нужно этим трём экранам.
 */
object HistoryLayout {

    /**
     * Доля высоты журнала, которую отбор забирает в самом большом случае.
     *
     * Срок, поиск и три ряда плашек в окне 960×640 занимали всю высоту,
     * и журнал не показывал ни одной строки. Отбор берёт свою высоту,
     * но не больше этой доли, а дальше прокручивается сам; строкам
     * остаётся не меньше остального.
     */
    const val HEAD_SHARE = 0.36f

    /**
     * Кнопка со словом в конце строки: «Z-отчёт», «Z-есеп».
     *
     * Столбец [TableColumns.action] рассчитан на значок; кнопке с надписью
     * нужно место под надпись крупной ступенью и поля ячейки.
     */
    val wordAction = 136.dp

    /**
     * Строка таблицы не ниже цели нажатия Material 3.
     *
     * Строку держит по высоте кнопка в её конце; у открытой смены кнопки
     * Z-отчёта нет, и её строка выходила вдвое ниже соседних.
     */
    val row = 48.dp

    /**
     * Плашка состояния доставки в журнале.
     *
     * Общего [TableColumns.status] не хватает казахскому «Қабылданбады»:
     * плашка в 109 точек на обычной ступени против 104 в столбце, и слово
     * рвалось посередине. Самое длинное слово состояния на трёх языках
     * с полями плашки и ячейки.
     */
    val deliveryStatus = 128.dp

    /**
     * Объяснение рядом с крупным числом в сводке очереди — не уже этого.
     *
     * Уже него объяснение вставало столбиком по два слова, пока кнопка
     * повтора держала свою ширину; теперь кнопка уходит под него.
     */
    val summaryNote = 280.dp
}
