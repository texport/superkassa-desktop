package kz.mybrain.superkassa.desktop.ui.components

import kz.mybrain.superkassa.desktop.server.DictionaryEntry

/**
 * Куда касса будет слать чеки: БФД и её контур.
 *
 * Адреса серверов БФД узел знает сам — по поставщику и контуру. Владелец
 * хост и порт не вводит: присланный клиентом адрес узел не принимает.
 *
 * Поставщик стоит подставленным, а не выбранным: в этом продукте он один.
 */
data class OfdTarget(
    val provider: String = BFD_PROVIDER,
    val environment: String = ""
) {
    /** Всё нужное для заведения кассы заполнено. */
    val complete: Boolean get() = provider.isNotBlank() && environment.isNotBlank()
}

/**
 * Код единственной базы фискальных данных этого продукта.
 *
 * Справочник узла называет и второго оператора, но касса заводится только
 * в БФД. Выбор из одного значения владельцу решать нечего, а чужой
 * оператор в списке кончался бы отказом узла уже после нажатия. Появится
 * второй — вместе с ним вернётся и список.
 */
const val BFD_PROVIDER = "BFD"

/**
 * Поднят ли контур, который называет справочник узла.
 *
 * Отвечает пока только стенд разработки. Спрятать остальные значило бы
 * обещать, что контур у БФД один; погасить — показать, что они есть
 * и ещё не отвечают. Узел о готовности контура не сообщает: справочник
 * перечисляет контуры протокола, а не поднятые серверы, — поэтому список
 * назван здесь и вычёркивается по мере запуска.
 */
fun DictionaryEntry.environmentRaised(): Boolean = supported && code !in unraisedEnvironments

private val unraisedEnvironments = setOf("TEST", "PROD")
