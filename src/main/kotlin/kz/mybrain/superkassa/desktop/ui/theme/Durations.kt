package kz.mybrain.superkassa.desktop.ui.theme

import kotlin.time.Duration
import kotlin.time.Duration.Companion.milliseconds
import kotlin.time.Duration.Companion.seconds

/**
 * Длительности интерфейса.
 *
 * Шкала одна на всё приложение, как отступы и размеры: подобранная
 * на месте пауза расходится от экрана к экрану, и кружок в одном разделе
 * появляется раньше, чем в соседнем.
 */
object Durations {

    /**
     * Сколько ждать, прежде чем показать признак работы.
     *
     * Узел на той же машине отвечает за десятки миллисекунд, и без паузы
     * кружок успевал мелькнуть на каждом нажатии — мигание раздражает
     * сильнее пустоты. Пауза короче того, что человек принимает за
     * задержку, поэтому настоящее ожидание она не прячет.
     */
    val beforeWaiting: Duration = 250.milliseconds

    /**
     * Сколько ждать после последнего набранного знака, прежде чем
     * спрашивать подсказки.
     *
     * Запрос на каждую букву — это пять обращений к кабинету на слово
     * «Алматы», и ответ на третью букву приходил после ответа на пятую,
     * подменяя собой уже уточнённый список. Пауза короче той, что человек
     * замечает между набором и появлением подсказки.
     */
    val afterTyping: Duration = 300.milliseconds

    /**
     * Как часто перечитывать то, за чем сейчас смотрят.
     *
     * Касса торгует, пока владелец смотрит на её сводку, и снятые
     * при открытии числа к концу разговора о ней уже неверны. Чаще —
     * и кабинет считал бы выручку сети по кругу без нужды: чек проходит
     * реже, чем за эти секунды.
     */
    val whileWatching: Duration = 20.seconds

    /**
     * Как часто двигается видимый отсчёт срока.
     *
     * Секунда: отсчёт, который стоит на месте, человек читает как
     * зависший экран — ровно то, от чего он и заведён.
     */
    val everySecond: Duration = 1.seconds

    /**
     * Сколько карта едет к выбранной кассе.
     *
     * Короче — и переход неотличим от прыжка, ради которого он и заведён;
     * длиннее — и владелец ждёт карту после каждого нажатия в списке.
     */
    val mapGlide: Duration = 450.milliseconds
}
