package kz.mybrain.superkassa.desktop.ui.theme

/**
 * Служебные знаки интерфейса.
 *
 * Тире вместо отсутствующего значения, точка между сведениями в одной
 * строке, многоточие обрезанного названия — это такие же элементы
 * оформления, как отступ и цвет, и живут они там же. Набранные на месте,
 * они расходились: в журнале строка шла через среднюю точку, в карточке
 * кассы — через точку с пробелами разной ширины, а пустое значение
 * оказывалось то тире, то дефисом, то пустотой.
 *
 * Знаки заданы кодовыми точками, а не набраны в файле: дефис, минус
 * и тире неразличимы глазом в редакторе, а на экране кассира дают
 * столбец разной длины.
 */
object Glyphs {

    /** Значения нет: прочерк, а не пустая клетка — пустота читается как недосмотр. */
    const val DASH: String = "\u2014"

    /** Между сведениями, которые стоят одной строкой. */
    const val SEPARATOR: String = " \u00B7 "

    /** Знак вычитания в сумме: настоящий минус, а не дефис переноса. */
    const val MINUS: String = "\u2212"

    /** Название не поместилось и обрезано. */
    const val ELLIPSIS: String = "\u2026"

    /**
     * Дробная часть отделяется запятой.
     *
     * Один знак на все числа экрана: деньги показывались через запятую,
     * а количество весового товара — через точку, и в одной строке чека
     * стояло «1.450 кг × 3 450,00 ₸».
     */
    const val DECIMAL: Char = ','

    /**
     * Неразрывный пробел.
     *
     * Держит вместе число и то, что при нём стоит: доля и знак процента,
     * разряды суммы. Обычный пробел здесь переносит знак на новую строку.
     */
    const val NBSP: Char = '\u00A0'
}
