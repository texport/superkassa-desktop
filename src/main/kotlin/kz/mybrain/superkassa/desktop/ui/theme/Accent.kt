package kz.mybrain.superkassa.desktop.ui.theme

/**
 * Основной тон кассы.
 *
 * Тон задаётся одним оттенком, а не набором цветов: по правилам
 * тональных палитр Material 3 из оттенка выводится вся схема — главная,
 * вторичная и третичная роли, поверхности, обводки. Так тона не
 * расходятся ни в контрасте, ни в яркости поверхностей: меняется только
 * оттенок, а тона остаются теми же.
 *
 * Оттенок задан углом в цветовом круге Lab, а не образцовым цветом:
 * из образца сначала пришлось бы вычислять тот же угол.
 *
 * Тонов четырнадцать, и это не круглое число ради круглого. Углы стоят
 * не через равные доли круга, а так, чтобы кружки в выборе не сливались:
 * в жёлто-зелёной четверти экран берёт полную насыщенность и соседние
 * углы расходятся далеко, а в бирюзово-синей насыщенность упирается
 * в границу экранных цветов, и там углы разнесены шире. Ближайшая пара —
 * изумрудный с бирюзовым — расходится на тринадцать единиц Lab, вшестеро
 * больше порога различения. Пятнадцатый тон пришлось бы ставить вдвое
 * теснее, то есть добавить кружок, неотличимый от соседнего.
 *
 * Индиго — тон по умолчанию: касса им и была, и без выбора её вид
 * не меняется. Порядок — по кругу от красного: ряд кружков читается
 * спектром, а не перечнем.
 */
enum class Accent(val code: String, val hue: Float) {

    Red("red", 30f),

    Orange("orange", 55f),

    Amber("amber", 80f),

    Olive("olive", 100f),

    Lime("lime", 125f),

    Green("green", 150f),

    Emerald("emerald", 172f),

    Teal("teal", 195f),

    Azure("azure", 225f),

    Blue("blue", 265f),

    Indigo("indigo", 294.5f),

    Violet("violet", 320f),

    Lilac("lilac", 339f),

    Pink("pink", 359f);

    companion object {
        fun byCode(code: String?): Accent = entries.firstOrNull { it.code == code } ?: Indigo
    }
}
