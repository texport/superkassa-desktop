package kz.mybrain.superkassa.desktop.ui.cabinet

/**
 * С какого запроса кабинет отдаёт подсказки.
 *
 * Правило одно на адресный регистр и на классификатор ОКЭД: однобуквенный
 * запрос кабинет отвергает, а пустой отдаёт начало справочника. Записанное
 * в каждом списке заново, оно уже начинало расходиться — и владелец видел
 * подсказки в одном поле и отказ в соседнем, набрав то же самое.
 *
 * @param needle набранное владельцем без окружающих пробелов.
 */
fun askableQuery(needle: String): Boolean =
    needle.isEmpty() || needle.length >= MIN_QUERY

/** Наименьший запрос, который кабинет принимает; короче — отказ. */
private const val MIN_QUERY = 2
