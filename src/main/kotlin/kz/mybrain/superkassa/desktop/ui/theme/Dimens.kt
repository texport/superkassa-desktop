package kz.mybrain.superkassa.desktop.ui.theme

import androidx.compose.material3.MaterialTheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.platform.LocalDensity
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Отступы кассы.
 *
 * Шкала одна на всё приложение: экраны собираются из этих пяти значений
 * и ничего своего не придумывают. Разъехавшиеся на пару точек поля видны
 * кассиру сразу, а найти причину в двадцати файлах с числами — нельзя.
 */
object Spacing {
    /** Зазор внутри строки: между значком и подписью. */
    val hairline = 4.dp

    /** Между соседними элементами одной группы. */
    val tight = 8.dp

    /** Между полями формы. */
    val snug = 12.dp

    /** Внутренний отступ карточки и между блоками экрана. */
    val normal = 16.dp

    /** Поля экрана и крупные разделители. */
    val roomy = 24.dp

    /**
     * Поле экрана: расстояние от рельса разделов и от краёв окна
     * до содержимого.
     *
     * Меньше «просторного»: рельс сам по себе отделяет разделы от работы,
     * и двойной воздух отодвигал чек от меню на треть ширины поля ввода.
     * Значение одно на все разделы — экраны не подбирают его на месте.
     */
    val screen = 12.dp
}

/**
 * Размеры элементов.
 *
 * Ширины полей заданы по смыслу вводимого, а не числом на месте: «сумма»
 * везде одной ширины, и колонки экранов сходятся сами собой.
 */
object Sizes {
    /** Количество товара — две-три цифры. */
    val fieldQuantity = 140.dp

    /** Цена позиции. */
    val fieldPrice = 180.dp

    /** Пин и короткий код. */
    val fieldPin = 160.dp

    /** Сумма денег и выбор роли. */
    val fieldAmount = 200.dp

    /** Вид оплаты и реквизиты кассы. */
    val fieldChoice = 220.dp

    /** Поля отраслевых реквизитов, скидка и наценка на чек. */
    val fieldForm = 240.dp

    /** Штрихкод. */
    val fieldBarcode = 320.dp

    /**
     * Название кассы со значком объяснения.
     *
     * Подпись «Своё название кассы» вместе со значком в поле формы
     * не помещалась и переносилась на вторую строку, поле вырастало
     * и уезжало от кнопок рядом.
     */
    val fieldName = 320.dp

    /**
     * Сколько ширины поля занимает не текст: рамка, отступы и значок списка.
     *
     * По этой величине считается, сколько букв поместится в строку выбора:
     * длинное название иначе переносится на вторую строку и обрезается рамкой.
     */
    val fieldTextInset = 64.dp

    /** Скругления шкалы форм Material 3. */
    val smallCorner = 8.dp
    val corner = 12.dp
    val largeCorner = 16.dp
    val hugeCorner = 28.dp

    /** Скругление плашки состояния. */
    val chipCorner = 6.dp

    /** Подъём диалога над содержимым. */
    val dialogElevation = 6.dp

    /** Колонка экрана входа: список касс и пин. */
    val loginColumn = 760.dp

    /** Значок пустого состояния. */
    val emptyIcon = 48.dp

    /**
     * Запас сегмента переключателя поверх самой длинной подписи: поля
     * кнопки и галочка выбранного значения.
     *
     * Ширина у всех сегментов одинаковая: подпись «Сатып алу» длиннее
     * «Сату» вдвое, и по содержимому кнопки вышли бы разного размера.
     */
    val segmentInset = 56.dp

    /** Толщина полосы прокрутки. */
    val scrollbar = 8.dp

    /** Высота полоски ожидания под шапкой: место под неё есть всегда. */
    val busyLine = 4.dp

    /**
     * Рост поля ввода и кнопки, стоящей с ним в одной строке.
     *
     * У `OutlinedTextField` Material 3 это 56 dp. Кнопка рядом ниже поля
     * на десять пикселей выглядит съехавшей, поэтому рост берётся отсюда
     * обеими, а не подбирается на месте.
     */
    val fieldHeight = 56.dp

    /** Наименьшая ширина рельса разделов — по Material 3. */
    val rail = 80.dp

    /**
     * Колонка списка касс в кабинете: название кассы с номером КГД под ним.
     *
     * Прежде она брала ширину поля ввода — совпали числом случайно.
     */
    val registerColumn = 320.dp

    /** Значок в шапке раздела: крупнее строчного, мельче пустого состояния. */
    val headerIcon = 40.dp

    /** Наименьшая ширина плитки счётчика: по ней ряд итогов решает, переноситься ли. */
    val counterTile = 140.dp

    /** Значок объяснения рядом с заголовком раздела. */
    val infoIcon = 18.dp

    /** Кружок ожидания внутри кнопки. */
    val busyCircle = 18.dp

    /** Подъём закреплённой полосы действия над прокручиваемым списком. */
    val barElevation = 3.dp

    /** Стартовый размер окна кассы. */
    val windowWidth = 1180.dp
    val windowHeight = 820.dp
}

/**
 * Показ печатной ленты.
 *
 * Лента Z-отчёта — тысячи точек по высоте, поэтому окно берёт почти весь
 * экран, а ширину ленты кассир меняет сам: узкая читается как бумага,
 * широкая даёт разобрать суммы.
 */
object Tape {
    /** Доля окна под диалог печатной формы. */
    const val DIALOG_FRACTION = 0.92f

    /** Ширина ленты при открытии. */
    val defaultWidth = 520.dp

    /** Пределы и шаг переключения ширины. */
    val minWidth = 320.dp
    val maxWidth = 1140.dp
    val widthStep = 100.dp

    /** На сколько точек прокручивается лента за щелчок колеса. */
    const val SCROLL_STEP = 60f

    /** Поле сверху и снизу ленты внутри окна. */
    val margin = 24.dp
}

/**
 * Сколько места поле с подписью держит над рамкой.
 *
 * `OutlinedTextField` Material 3 поднимает подпись на рамку и заранее
 * оставляет над рамкой половину строки `bodySmall`, поэтому поле выше своей
 * рамки, а рамка прижата к его низу. Элемент, стоящий в строке с полем,
 * берёт тот же запас сверху: иначе он центрируется по всему полю и стоит
 * выше рамки на половину запаса.
 */
@Composable
fun fieldLabelReserve(): Dp = with(LocalDensity.current) {
    MaterialTheme.typography.bodySmall.lineHeight.toDp() / 2
}
