package kz.mybrain.superkassa.desktop.ui.settings

/**
 * Адрес службы, набранный руками.
 *
 * Поля адреса узла и адреса кабинета принимали любую непустую строку.
 * Набранный без схемы «192.168.50.35:17700» приложение не может даже
 * разобрать, а на экране кассира это выходило как «узел недоступен»:
 * владелец шёл искать сеть и сервер, тогда как искать нужно было
 * собственную опечатку в поле рядом. Отказ здесь дешевле того отказа
 * на четыре порядка.
 *
 * Правило сознательно грубое: схема, отсутствие пробелов внутри и хоть
 * что-то на месте хозяина. Годность адреса проверяет обращение по нему,
 * а здесь отсекается то, по чему обращения не будет вовсе.
 */
internal object ServiceAddress {

    /** Схемы, по которым приложение умеет обращаться. */
    private val SCHEMES = listOf("http://", "https://")

    /**
     * Адрес в том виде, в каком он уходит в настройки.
     *
     * Пробелы по краям приходят из буфера обмена вместе со скопированной
     * строкой, а косая черта на конце удваивалась бы с путём обращения.
     */
    fun tidy(text: String): String = text.trim().trimEnd('/')

    /** Годен ли адрес для обращения. Пустой — тоже не годен. */
    fun valid(text: String): Boolean {
        val address = tidy(text)
        if (address.isEmpty()) return false
        val scheme = SCHEMES.firstOrNull { address.startsWith(it, ignoreCase = true) } ?: return false
        val host = address.drop(scheme.length)
        return host.isNotEmpty() && host.none(Char::isWhitespace)
    }

    /**
     * Набранное стоит сохранять: адрес годен и отличается от записанного.
     *
     * Сохранять то же самое незачем, и живая кнопка над несохранённым
     * адресом — единственное, что отличает одно от другого на экране.
     */
    fun changed(text: String, saved: String): Boolean = valid(text) && tidy(text) != saved
}
