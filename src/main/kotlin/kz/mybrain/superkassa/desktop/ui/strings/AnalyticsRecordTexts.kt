package kz.mybrain.superkassa.desktop.ui.strings

/**
 * Надписи вкладки «Учёт касс».
 *
 * Вкладка отвечает на вопрос о парке касс в целом: сколько их заведено,
 * сколько КГД поставил на учёт, кому отказал и как это разложено
 * по регионам. Разговор свой — заявления, учёт и отказы, — и в наборе
 * карты эти строки терялись бы среди источников положения.
 *
 * Значения лежат своими файлами по языкам, а не внутри языковых файлов
 * аналитики: те и без того держат по полторы сотни строк, и ещё один
 * набор внутри них перестал бы читаться.
 *
 * Четырёх смыслов учёта здесь нет: они названы один раз плашками отбора
 * карты (`markOnRecord` и соседние), и вкладка зовёт их теми же словами.
 * Второй перевод тех же четырёх состояний разошёлся бы с первым.
 */
data class AnalyticsRecordTexts(
    val tab: String,

    /** Карточка с главными числами парка: заголовок и что за ними стоит. */
    val title: String,
    val hint: String,

    val total: String,
    val places: String,

    /**
     * Работает ли парк прямо сейчас: открытые смены и блокировки.
     *
     * Торгующие считаются из стоящих на учёте, и [tradingOf] говорит,
     * из скольких: «Сейчас торгуют 0» без основания читается как
     * остановившаяся сеть.
     */
    val trading: String,
    val tradingOf: String,
    val blocked: String,

    /**
     * Отказы КГД — единственное, по чему владелец действует сам.
     *
     * Поэтому они названы отдельно и стоят выше разреза по регионам.
     * Отсутствие отказов тоже сказано словами: пустое место под
     * заголовком читалось бы как несчитанное.
     */
    val refusals: String,
    val refusalsHint: String,
    val refusalsNone: String,

    /**
     * Разрез по регионам: заголовок и объяснение.
     *
     * Подписей столбцов здесь нет: «Регион», «Точек» и «Касс» уже
     * названы в наборах сводки и карты, и второй перевод тех же слов
     * разошёлся бы с первым.
     */
    val regions: String,
    val regionsHint: String
)

/** Надписи учёта касс на выбранном языке. */
fun analyticsRecordTexts(language: Language): AnalyticsRecordTexts = when (language) {
    Language.Kk -> analyticsRecordTextsKk
    Language.Ru -> analyticsRecordTextsRu
    Language.En -> analyticsRecordTextsEn
}
