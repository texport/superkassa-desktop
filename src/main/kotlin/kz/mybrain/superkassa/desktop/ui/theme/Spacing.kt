package kz.mybrain.superkassa.desktop.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Отступы кассы.
 *
 * Шкала одна на всё приложение: экраны собираются из этих пяти значений
 * и ничего своего не придумывают. Разъехавшиеся на пару точек поля видны
 * кассиру сразу, а найти причину в двадцати файлах с числами — нельзя.
 */
object Spacing {
    /** Зазор внутри строки: между значком и подписью. */
    val hairline = 4.dp

    /** Между соседними элементами одной группы. */
    val tight = 8.dp

    /** Между полями формы. */
    val snug = 12.dp

    /** Внутренний отступ карточки и между блоками экрана. */
    val normal = 16.dp

    /** Поля экрана и крупные разделители. */
    val roomy = 24.dp

    /**
     * Поле экрана: расстояние от рельса разделов и от краёв окна
     * до содержимого.
     *
     * Меньше «просторного»: рельс сам по себе отделяет разделы от работы,
     * и двойной воздух отодвигал чек от меню на треть ширины поля ввода.
     * Значение одно на все разделы — экраны не подбирают его на месте.
     */
    val screen = 12.dp
}
