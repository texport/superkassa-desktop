package kz.mybrain.superkassa.desktop.ui.strings

/**
 * Слова отбора касс — одни и те же на карте аналитики и в колонке точек.
 *
 * Состояние учёта владелец спрашивает в двух местах: на карте, где он
 * смотрит на хозяйство целиком, и в колонке торговых точек, где работает
 * с одной кассой. Два набора слов об одном и том же заставили бы его
 * учить два языка — «Заявление в КГД» на карте и что-нибудь своё
 * в колонке про то же самое состояние.
 *
 * Поэтому набор объявлен отдельно от обоих разделов и лежит в них обоих
 * одним и тем же значением: и `AnalyticsTexts.sieve`, и `CabinetTexts.sieve`
 * берут его у [sieveTexts].
 */
data class SieveTexts(

    /**
     * Учёт КГД пятью смыслами и «любой» шестым.
     *
     * Созданная касса и поданное заявление названы порознь: «учёт идёт»
     * обещало заявление в КГД у кассы, которую владелец только создал.
     *
     * Созданная называется черновиком — тем же словом, каким названа
     * плашка состояния в строке этой же кассы: два слова об одном
     * состоянии в одном списке владелец принял бы за два разных.
     */
    val allRecords: String,
    val onRecord: String,
    val entered: String,
    val applied: String,
    val refused: String,
    val deregistered: String,

    /** Признаки кассы помимо учёта: открытая смена и блокировка. */
    val shiftOpen: String,
    val blocked: String,

    /**
     * Под отбор ничего не подошло.
     *
     * Не то же, что пустое хозяйство: владельцу с двумя тысячами точек
     * «заведите первую точку» говорит о его деле неправду.
     */
    val empty: String,
    val emptyHint: String,
    val clear: String
)

/** Слова отбора выбранного языка. */
fun sieveTexts(language: Language): SieveTexts = when (language) {
    Language.Kk -> sieveTextsKk
    Language.Ru -> sieveTextsRu
    Language.En -> sieveTextsEn
}
