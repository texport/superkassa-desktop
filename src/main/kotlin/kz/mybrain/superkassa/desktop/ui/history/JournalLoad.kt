package kz.mybrain.superkassa.desktop.ui.history

/**
 * Чем кончилось чтение страницы документов.
 *
 * Три разных исхода, а не один: страница пришла и за ней есть ещё,
 * прочитано всё, прочитать не удалось. Прежде чтение отвечало одним
 * «продолжать ли», и отказ узла доходил до кассира тем же, чем пустой
 * день, — надписью «ничего нет». Кассир при этом стоял перед покупателем
 * с чеком в руках и искал несуществующую беду с чеком.
 */
enum class JournalLoad {
    /** Страница пришла полной: за ней есть ещё. */
    More,

    /** Прочитано всё, что у источника есть. */
    Whole,

    /** Прочитать не удалось: касса не выбрана, узел молчит или отказал. */
    Failed;

    /** Есть ли за прочитанным ещё страницы. */
    val more: Boolean get() = this == More

    /** Не удалось ли чтение: пустота после отказа — не пустота. */
    val failed: Boolean get() = this == Failed
}

/** Исход чтения страницы по её размеру: полная страница — значит есть ещё. */
internal fun pageLoad(loaded: Int, page: Int): JournalLoad =
    if (loaded == page) JournalLoad.More else JournalLoad.Whole
