package kz.mybrain.superkassa.desktop.ui.history

import java.math.BigDecimal

/**
 * Строка журнала документов — одна и та же для узла и для кабинета.
 *
 * Журнал кассы и документы кассы в кабинете показывают одно и то же:
 * когда документ пробит, чем он является, на сколько он и что с ним стало.
 * Различаются только источники — узел рядом и сервер приёма данных за сетью.
 * Поэтому оба приводят свои записи к этому типу, а показ, поиск, отбор
 * и порядок строк написаны один раз.
 *
 * Рядом с каждым показываемым значением лежит то, по которому строка
 * сортируется: «4 500,00 ₸» и «1 200,00 ₸» по тексту идут в обратном
 * порядке, а по сумме — в прямом.
 *
 * @param key чем строка отличается от соседней в списке.
 * @param at время документа числом: по нему строки идут по времени.
 * @param moment время документа словами.
 * @param typeCode код вида документа: по нему идёт отбор.
 * @param type вид документа словами.
 * @param numberOrder номер числом; у записи без номера его нет.
 * @param amountOrder сумма числом, а не текстом.
 * @param sign фискальный признак или то, что источник знает вместо него.
 * @param about остальное, по чему ищут строку: наименования позиций,
 *   кассир, отметка КГД. В столбцах этого нет — искать по нему нужно.
 * @param refusal почему документ отвергнут — словами кассира и кодом
 *   отказа; `null`, если отказа нет или источник причины не отдаёт.
 *   В столбец она не помещается и стоит подсказкой у плашки, но искать
 *   по ней нужно: «все отказы из-за одного и того же» — обычный вопрос
 *   обслуживанию.
 * @param printable есть ли у документа печатная форма.
 */
data class JournalEntry(
    val key: String,
    val at: Long?,
    val moment: String,
    val typeCode: String?,
    val type: String,
    val number: String,
    val numberOrder: Long?,
    val amount: String,
    val amountOrder: BigDecimal?,
    val sign: String,
    val delivery: JournalDelivery?,
    val shiftNo: Long?,
    val state: JournalState? = null,
    val about: String = "",
    val refusal: String? = null,
    val printable: Boolean = true
) {

    /**
     * По чему ищет строка поиска: всё показанное и [about] вдобавок.
     *
     * Сумма попадает сюда дважды — как она напечатана и как её набирают:
     * «4 500,00 ₸» с разделителем разрядов по «4500» не находится, а ищут
     * именно так.
     */
    val searchable: String
        get() = listOf(
            number,
            amount,
            amountOrder?.toPlainString().orEmpty(),
            sign,
            type,
            moment,
            shiftNo?.toString().orEmpty(),
            about,
            refusal.orEmpty()
        ).joinToString(" ").lowercase()
}

/** Вид документа для отбора: код для сравнения, слово для чипа. */
data class JournalType(val code: String, val title: String)

/**
 * Состояние самой записи, когда о доставке говорить нечего.
 *
 * Смена в ОФД не «доставляется» — она открыта или закрыта, — и красить её
 * состояние словами доставки значило бы обещать владельцу не то. Поэтому
 * у такой записи своё слово и один признак: сделано или ещё идёт.
 */
data class JournalState(val title: String, val done: Boolean)

/**
 * Что сказать, когда источник не отдал ни одной строки.
 *
 * Слова у источников разные: узел за этот день не пробил ни чека,
 * а кабинет о кассе ещё ничего не принял, — и общее «нет данных»
 * не объясняет ни того, ни другого.
 */
data class JournalEmpty(val title: String, val hint: String)
