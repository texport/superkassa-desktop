package kz.mybrain.superkassa.desktop.ui.analytics

/**
 * Регион из адреса торговой точки.
 *
 * Своего поля региона ни у точки, ни у кассы нет, а адрес кабинета
 * записан как «Регион, Район, Улица, Дом» — значит, регион и есть первое
 * звено до запятой. Разбор объявлен один раз на весь раздел: по региону
 * складываются и выручка сети, и учёт касс, и разойдись эти два разбора,
 * одна и та же область называлась бы на двух вкладках по-разному.
 *
 * Адреса нет вовсе — так и сказано словами: выбросить такую строку
 * из свода нельзя, её кассы входят в парк наравне с остальными.
 */
fun regionOf(address: String?, unknown: String): String =
    address?.substringBefore(',')?.trim()?.takeIf { it.isNotBlank() } ?: unknown
