package kz.mybrain.superkassa.desktop.app

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/**
 * Печатная форма, открытая кассиром: картинка и ожидание её.
 *
 * Отдельный предмет от прочего состояния рабочего места, потому что живёт
 * не по ходу работы, а по ходу одного нажатия: узел рисует форму секунду-две,
 * и всё это время на экране должно стоять ожидание, а не пустое окно.
 *
 * Держится в сеансе, а не на экране: печать идёт секунду-другую, кассир
 * успевает уйти в другой раздел, и запущенное экраном обращение обрывалось
 * вместе с ним — форма не открывалась вовсе.
 */
class PrintPreview {

    /** Нарисованная форма; `null` — показывать нечего. */
    var image: ByteArray? by mutableStateOf(null)

    /**
     * Узел сейчас рисует печатную форму.
     *
     * Окно просмотра открывается по нажатию, а не по готовой картинке:
     * рисование длится секунду-две, и без этого нажатие не отзывалось
     * ничем. Признак снимается и по картинке, и по отказу.
     */
    var drawing: Boolean by mutableStateOf(false)

    /**
     * Узел формы не нарисовал.
     *
     * Держится рядом с картинкой, а не вместо неё: окно остаётся
     * открытым и само говорит, что случилось. Прежде оно исчезало
     * целиком, а причина оставалась одной строкой внизу экрана —
     * и владелец, закрывший её, уже не узнавал, почему чек не показали.
     */
    var trouble: PreviewTrouble? by mutableStateOf(null)
}

/**
 * Отказ узла по печатной форме и то, чем его повторить.
 *
 * Слова берутся у отказавшего: своя формулировка поверх чужого отказа
 * скрыла бы причину. Их может не быть вовсе — тогда в окне стоит
 * одно название беды.
 */
data class PreviewTrouble(val words: String?, val again: () -> Unit)
