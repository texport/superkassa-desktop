package kz.mybrain.superkassa.desktop.server.cabinet

/**
 * Длина страницы списка в кабинете.
 *
 * Отдельным предметом, а не полем одного из списков: размер страницы один
 * и тот же у чеков, смен, отчётов, движений денег, точек, касс и справочников.
 * Лежащий рядом с чеками, он читался бы как свойство чеков — и второй список
 * завёл бы своё число.
 */
const val PAGE_SIZE: Int = 50

/**
 * Список кабинета целиком, страница за страницей.
 *
 * Точки, кассы и модели читаются не по кнопке «показать ещё», а разом:
 * по ним идёт поиск в колонке и выбор в заявлении, и список, оборванный
 * на первой странице, отвечает «ничего не нашлось» о кассе, которая
 * у владельца есть. У сети это уже не мелочь: две тысячи точек — сорок
 * страниц, а до правки владелец видел пятьдесят первых.
 *
 * Документы читаются иначе, страницами по кнопке (`DocumentListState`):
 * чеков у кассы десятки тысяч, и все сразу не нужны никому.
 *
 * Прочитанное отдаётся после каждой страницы, а не в конце: сорок
 * страниц сети — это секунды, и всё это время экран стоял бы в ожидании,
 * хотя первые пятьдесят точек уже пришли. Сколько их всего, кабинет
 * говорит на первой же странице, и по этому числу видно, что список ещё
 * заполняется.
 *
 * @param read чтение одной страницы по её номеру.
 * @param onPart прочитанное на сейчас и сколько записей всего у кабинета.
 */
internal suspend fun <T> allPages(
    read: suspend (Int) -> CabinetPage<T>,
    onPart: (List<T>, Long) -> Unit = { _, _ -> }
): List<T> {
    val first = read(0)
    val all = first.items.toMutableList()
    onPart(all.toList(), first.totalElements)
    var page = 1
    while (all.size < first.totalElements && page < PAGE_LIMIT) {
        // Пустая страница раньше объявленного числа — конец списка:
        // крутиться до предела, пока кабинет отдаёт пустоту, незачем.
        val next = read(page).items
        if (next.isEmpty()) break
        all += next
        onPart(all.toList(), first.totalElements)
        page++
    }
    return all
}

/**
 * Сколько страниц читается подряд, прежде чем остановиться.
 *
 * Предел на случай, когда кабинет объявит в `totalElements` больше, чем
 * отдаёт: без него чтение крутилось бы, пока владелец не закроет окно.
 * Двухсот страниц хватает на десять тысяч записей — вчетверо больше того,
 * что ожидается у самой крупной сети.
 */
private const val PAGE_LIMIT = 200
