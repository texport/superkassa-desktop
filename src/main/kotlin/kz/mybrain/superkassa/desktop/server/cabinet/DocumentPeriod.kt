package kz.mybrain.superkassa.desktop.server.cabinet

import java.time.Instant

/**
 * Границы периода, за который кабинет отдаёт документы.
 *
 * Кабинет отбирает по моменту приёма документа сервером и принимает обе
 * границы включительно; пустая граница означает «без ограничения».
 * Момент передаётся строкой ISO-8601 в UTC — так его ждёт кабинет,
 * и так он не зависит от часового пояса рабочего места.
 *
 * Тип общий на все виды документов: у чеков границы уходят телом отбора,
 * у отчётов и движения денег — параметрами запроса, но период у них один
 * и тот же, и считать его дважды значило бы разойтись в границах суток.
 */
data class DocumentPeriod(val from: Instant? = null, val to: Instant? = null) {

    /** Хвост запроса: пустой период не добавляет ни одного параметра. */
    fun query(): String = listOfNotNull(
        from?.let { "&dateFrom=$it" },
        to?.let { "&dateTo=$it" }
    ).joinToString("")

    /** Границы строками для тела отбора чеков. */
    fun fromText(): String? = from?.toString()

    fun toText(): String? = to?.toString()
}
