package kz.mybrain.superkassa.domain.signin.port

import io.github.texport.superkassa.core.presentation.api.model.kkm.KkmResponse
import kz.mybrain.superkassa.domain.signin.model.Seat

/**
 * Касса, за которой сейчас работают, — глазами сценария области.
 *
 * Сценарий, которому для команды нужны касса и пин, берёт их здесь в момент
 * вызова, а не получает параметрами от модели экрана: пин не проходит через
 * экраны, и все сценарии спрашивают кассу одинаково. Отсюда нельзя ни войти,
 * ни выйти — только узнать, кто за кассой, и отдать всем разделам то, что
 * касса сказала о себе.
 *
 * Реализует держатель входа `SignIn`: вход живёт в памяти процесса,
 * и второй реализации, кроме тестовых, у порта нет.
 */
interface SignedKkm {

    /** Касса и пин для команды; `null` — за кассой никто не работает. */
    fun seat(): Seat?

    /** Касса ответила о себе: её новое состояние видят шапка, вход и все разделы. */
    fun refresh(kkm: KkmResponse)
}
