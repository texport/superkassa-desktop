package kz.mybrain.superkassa.domain.journal.model

/**
 * Сколько записей журнала касса отдаёт за одно обращение.
 *
 * Ядро принимает страницу от одной до пятисот записей и на большее
 * отвечает отказом `PAGE_LIMIT_OUT_OF_RANGE`. Журнал дочитывает срок
 * страницами: за месяц оживлённой кассы документов десятки тысяч.
 */
object DocumentPages {

    /** Документов за раз: журнал за срок и документы смены. */
    const val DOCUMENTS: Int = 200

    /** Смен за раз: касса, которой год, показывает историю страницами. */
    const val SHIFTS: Int = 200

    /** Больше этого ядро за раз не отдаёт. */
    const val CORE_LIMIT: Int = 500
}
