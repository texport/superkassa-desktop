package kz.mybrain.superkassa.domain.shift.model

/**
 * Состояние смены со слов кассы.
 *
 * Третье состояние здесь не лишнее: пока касса не ответила, приложение
 * не знает про смену ничего, и говорить за неё «закрыта» нельзя.
 */
enum class ShiftState {
    /** Касса ещё не отвечала либо ответить не смогла. */
    Unknown,
    Open,
    Closed
}
