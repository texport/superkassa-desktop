package kz.mybrain.superkassa.domain.cabinet.model.documents

/**
 * Пакет протокола, приложенный к документу кабинета.
 *
 * Отдельный предмет, потому что он один и тот же у чека, отчёта и движения
 * денег: пакет — запрос кассы и ответ ОФД на него — это всё, что о документе
 * известно вне кассы, где он пробит, и по нему рисуется печатная форма.
 */
internal interface ProtocolDocument {

    /** Пакет текстом, готовым уйти на печать; `null` — кабинет его не отдал. */
    val packet: String?
}
