package kz.mybrain.superkassa.domain.update.model

/**
 * Установщик новой версии под эту систему.
 *
 * @property name имя файла выпуска.
 * @property url откуда его скачивать.
 * @property sha256 контрольная сумма, объявленная выпуском; `null` —
 *   выпуск её не объявил, и скачанное сверить не с чем.
 */
data class Installer(val name: String, val url: String, val sha256: String?) {

    /**
     * Скачанное можно сверить с выпуском.
     *
     * Установщик ставится с правами владельца машины: подменённый по дороге
     * файл получил бы кассу целиком. Без объявленной суммы касса его не
     * скачивает, а открывает страницу выпуска.
     */
    val verifiable: Boolean get() = !sha256.isNullOrBlank()
}

/** Чем кончилось скачивание установщика. */
sealed interface Fetched {

    /** Скачан, и сумма совпала с объявленной выпуском. */
    data class Verified(val file: String) : Fetched

    /** Скачан, но сумма не совпала: файл удалён, ставить его нельзя. */
    data object Mismatch : Fetched

    /** Скачать не удалось; причина — для журнала. */
    data class Failed(val reason: String) : Fetched
}

/** Чем кончилась установка, начатая кассиром. */
enum class InstallOutcome {
    /** Установщик скачан, сверен и открыт: дальше ставит кассир. */
    Started,

    /** Сверить нечем или своего установщика нет: открыта страница выпуска. */
    PageOpened,

    /** Скачанный установщик не совпал с выпуском и удалён. */
    Tampered,

    /**
     * Система не разрешила кассе ставить приложения: открыта её настройка,
     * а скачивание не начиналось — после разрешения кассир нажимает снова.
     */
    NeedsPermission,

    /** Скачать или открыть не удалось. */
    Failed
}
