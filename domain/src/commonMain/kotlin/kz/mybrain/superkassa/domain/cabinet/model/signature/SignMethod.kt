package kz.mybrain.superkassa.domain.cabinet.model.signature

/**
 * Чем владелец подписывает: способ выбирает он сам, а платформа
 * предлагает только то, что на ней работает.
 */
enum class SignMethod {
    /** NCALayer на этой машине — настольные системы: окно подписи показывает сам NCALayer. */
    NcaLayer,

    /**
     * Приложение eGov mobile — на этом устройстве или на телефоне по QR:
     * ключ остаётся в eGov mobile, касса получает только подпись.
     */
    EgovMobile,

    /** Файл ключа `.p12` на этом устройстве и пароль к нему, который вводится при каждой подписи. */
    KeyFile
}
