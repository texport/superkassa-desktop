package kz.mybrain.superkassa.strings.api.kassa

/**
 * Единицы измерения по коду классификатора ИС ЭСФ — сокращённо и на языке
 * кассира.
 *
 * Перечень единиц — у ядра, но слова у него только русские и казахские,
 * и английский интерфейс показывал «шт» и «кг». Названия заведены здесь
 * по коду: код — общий для всех трёх языков и для чека, слово — надпись
 * экрана.
 *
 * @property names сокращение единицы по её коду.
 */
data class UnitTexts(val names: Map<String, String>) {
    /**
     * Сокращение единицы с кодом [code].
     *
     * @return сокращение; `null` — код приложению незнаком, и его показывают
     *   как есть: спрятать его значило бы показать количество без единицы.
     */
    fun short(code: String): String? = names[code]
}
