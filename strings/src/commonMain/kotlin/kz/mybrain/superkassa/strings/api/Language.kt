package kz.mybrain.superkassa.strings.api

/**
 * Язык интерфейса.
 *
 * Казахский стоит первым: это государственный язык, и касса работает
 * в Казахстане. Название каждого языка написано на нём самом — так его
 * узнают, не зная двух других.
 *
 * @property code код языка по ISO 639-1: так язык хранится в настройках
 *   и так его называет система.
 * @property title название языка на нём самом — для выбора языка.
 */
enum class Language(val code: String, val title: String) {
    Kk("kk", "Қазақша"),
    Ru("ru", "Русский"),
    En("en", "English");

    /**
     * Слова, пришедшие сразу на трёх языках, — на этом.
     *
     * Справочники ядра и отказы кассы говорят сразу на трёх языках, и выбирать
     * нужный обязан один код, а не каждый экран по-своему. Пустое на казахском
     * или английском подменяется русским: чужой язык лучше пустой строки.
     * Пустое и по-русски — не слова: `null`, и экран берёт своё.
     */
    fun choose(ru: String, kk: String, en: String): String? = when (this) {
        Ru -> ru
        Kk -> kk.ifBlank { ru }
        En -> en.ifBlank { ru }
    }.takeIf { it.isNotBlank() }

    /** Выбор языка по коду. */
    companion object {
        /**
         * Язык рабочего места: выбранный владельцем, иначе язык системы.
         *
         * Язык не выбран только на свежем рабочем месте, и показывать там
         * государственный язык машине, настроенной по-русски, значит
         * встречать владельца мастером на языке, которого он не просил.
         * Система чужого языка — тот же случай: остаётся государственный.
         *
         * @param code код языка, выбранного владельцем; `null` — не выбран.
         * @param system код языка системы; его спрашивает приложение,
         *   у модуля текстов своего способа узнать язык машины нет.
         */
        fun byCode(code: String?, system: String?): Language =
            entries.firstOrNull { it.code == code }
                ?: entries.firstOrNull { it.code == system }
                ?: Kk
    }
}
