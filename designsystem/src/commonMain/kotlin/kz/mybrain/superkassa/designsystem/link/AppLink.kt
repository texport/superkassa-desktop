package kz.mybrain.superkassa.designsystem.link

import androidx.compose.runtime.Composable

/**
 * Открыватель ссылки — по возможности прямо в приложении [app].
 *
 * Ссылку вида `https://…` Android отдаёт приложению, только если оно
 * закрепило за собой её адрес; иначе открывается браузер, и владелец,
 * ждавший перехода в приложение, видит, что «ничего не происходит».
 * Поэтому на Android ссылка сперва адресуется самому приложению, а без
 * него — всякому, кто её откроет. На компьютере и iOS ссылку открывает
 * система.
 *
 * @param app имя пакета приложения Android; на других системах не нужно.
 * @return открыватель: `true` — ссылку есть кому открыть, `false` — некому,
 *   и экран должен сказать об этом, а не молчать.
 */
@Composable
expect fun rememberAppLink(app: String): (String) -> Boolean
