package kz.mybrain.superkassa.designsystem.theme.size

/**
 * Раскладка аналитики кабинета: карта и таблицы.
 *
 * Общие приёмы — доли панелей, наименьшие столбцы, пределы ширины — живут
 * в [Panes], [TableColumns] и [ContentWidths]. Здесь только то, чего
 * у других разделов нет: карта касс со своей сеткой мест и столбцы,
 * которые встречаются лишь в сводках аналитики.
 */
object AnalyticsLayout {

    /**
     * Ниже этого карта не сжимается.
     *
     * Столько занимает управление в её углу — «где я», приближение,
     * отдаление и «во весь экран» — с полями. В низком окне ряды отбора
     * над картой отнимали у неё всю высоту, и при выбранной кассе карта
     * пропадала вовсе. Теперь, если над картой тесно, раздел прокручивается,
     * а карта остаётся картой.
     */
    val mapLeast = 60.steps

    /**
     * Сторона клетки, в которой кассы сводятся в один кружок.
     *
     * Чуть больше самого крупного кружка ([Sizes.mapMarkCrowd]), и кружок
     * не выходит за свою клетку: соседние не наезжают друг на друга.
     * Задана в точках интерфейса, как и сами кружки: на экране с двойной
     * плотностью клетка в точках полотна была вдвое меньше кружка,
     * и кружки ложились один на другой.
     */
    val mapCell = 16.steps

    /**
     * Название области в таблице учёта.
     *
     * Самое длинное — «Солтүстік Қазақстан облысы» — встаёт целиком
     * и на крупной ступени; уже этого столбца таблица прокручивается вбок.
     */
    val regionName = 60.steps

    /**
     * Число учёта под подписью смысла: «Есептен шығарылған»,
     * «МКК-ға өтініш берілген».
     *
     * Шире счёта штук ([TableColumns.count]): подпись над числом в две
     * строки встаёт по словам, а не обрывается многоточием.
     */
    val recordMeaning = 30.steps

    /**
     * Сумма по сети, точке или области в сводке торговли.
     *
     * Шире обычного столбца суммы ([TableColumns.money]): у сети суммы
     * идут на миллиарды тенге, и «98 797 031 109,99 ₸» встаёт своей
     * ступенью, а не самой мелкой.
     */
    val networkSum = 190.fine
}
