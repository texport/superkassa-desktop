package kz.mybrain.superkassa.designsystem.theme.color

/**
 * Непрозрачность содержимого по Material 3.
 *
 * Выключенное содержимое Material 3 рисует на 38 %: так гаснут кнопка
 * и переключатель. Подпись строки рядом с ними гаснет тем же числом,
 * а не своим, иначе строка и её переключатель читаются по-разному.
 */
object ContentAlpha {
    /** Обычное содержимое. */
    const val FULL = 1f

    /** Выключенное: то, что сейчас не нажать. */
    const val DISABLED = 0.38f
}
