/**
 * Общее экранов кассы: то, что берут несколько областей и что знает домен.
 *
 * Помощники моделей экранов — разговор с кассиром, занятость, общие службы
 * окна и хранилище моделей; деньги словами, строка сообщений, состояние
 * кассы, слова типов домена и ядра, таблица документов и период журнала,
 * карта, выбор языка и темы вида окна; контракты между областями —
 * печать документа, место точки на карте и шаги кабинета для мастера.
 *
 * Модуль знает домен и дизайн-систему, но ни одной области: области берут
 * общее отсюда, а друг друга не видят вовсе — это держит граф модулей.
 */
kotlin {
    sourceSets {
        commonMain.dependencies {
            // Типы домена, дизайн-системы и моделей экранов стоят в открытых
            // объявлениях общего: сценарии, токены, хранилище моделей окна.
            api(project(":domain"))
            api(project(":designsystem"))
            // Ключи экранов и переход по ним: область открывает соседку
            // по ключу, не видя её.
            api(project(":navigation"))
            api(libs.lifecycle.viewmodel.compose)
            implementation(libs.lifecycle.runtime.compose)
        }
    }
}
