package kz.mybrain.superkassa.domain.print.model

/**
 * Отказы кассы, которые лечатся пином.
 *
 * Решает код отказа, а не сам факт отказа: касса отказывает по печатной
 * форме и по другим поводам — документа нет, рисовать нечем, — и вопрос
 * о пине поверх такого отказа выдавал бы причину за неверный пин.
 */
object PinRefusal {

    /** Пин неверный или не даёт прав: поможет другой. */
    val WRONG: Set<String> = setOf("USER_NOT_FOUND", "USER_FORBIDDEN", "FORBIDDEN")

    /** Пин набирали неверно слишком часто: касса ждёт, прежде чем спросить снова. */
    const val LOCKED = "PIN_LOCKED"

    /** Что делать с пином, введённым ради печатной формы, после отказа кассы. */
    enum class Next {
        /** Пин неверный: забыть его и спросить снова. */
        AskAgain,

        /** Пин заблокирован: забыть, но не спрашивать — касса ждёт и говорит, сколько. */
        Forget,

        /** Отказ не по пину: пин верный, его не трогать. */
        Keep
    }

    /** Что делать с пином после отказа с кодом [code]. */
    fun next(code: String): Next = when (code) {
        in WRONG -> Next.AskAgain
        LOCKED -> Next.Forget
        else -> Next.Keep
    }
}
