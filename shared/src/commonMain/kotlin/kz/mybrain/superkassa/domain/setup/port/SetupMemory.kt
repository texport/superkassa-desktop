package kz.mybrain.superkassa.domain.setup.port

/**
 * Где мастер подключения кассы держит пройденное между запусками.
 *
 * Подключение бросают на середине: номер получили сегодня, ключ ЭЦП
 * принесли через неделю. Значения живут на диске рабочего места,
 * поимённо: имена появляются вместе с шагами мастера.
 *
 * Токен кассы сюда не пишется никогда: это ключ, которым касса подписывает
 * запросы.
 */
interface SetupMemory {

    /** Записанное под [name]; `null` — не записано. */
    fun setupValue(name: String): String?

    /** Записывает [value] под [name]; `null` стирает запись. */
    fun setupValue(name: String, value: String?)
}
