package kz.mybrain.superkassa.domain.cabinet.model

/**
 * Своё название кассы у владельца — заметка для него, в БФД не уходит.
 *
 * Кабинет требует название всегда: не пустое и не длиннее [MAX_LENGTH].
 * Стереть его он не даёт — и пустое, и отсутствующее поле он отвергает
 * проверкой полей, — поэтому пустое сюда не пропускается вовсе.
 */
object RegisterName {
    /** Сколько знаков кабинет принимает в названии. */
    const val MAX_LENGTH: Int = 120

    /** Название к отправке; `null` — такое кабинет не примет: пустое или длиннее предела. */
    fun of(typed: String): String? = typed.trim().takeIf { it.isNotEmpty() && it.length <= MAX_LENGTH }
}
