package kz.mybrain.superkassa.domain.kassa.model

/**
 * Почему касса не открылась при запуске.
 *
 * Причины разведены по тому, что делать кассиру или владельцу: закрыть
 * прежний узел, закрыть второе окно, позвать обслуживание. Пустую кассу
 * вместо данных прежнего узла приложение не открывает: она выглядела бы
 * как потерянные смены и чеки и толкала бы к повторной регистрации.
 */
enum class StartRefusal {

    /** Прежний узел кассы ещё работает над своей базой: перенос его данных не начат. */
    NodeRunning,

    /** Касса уже открыта в другом окне на этой машине. */
    KassaRunning,

    /** У кассы уже своя база, а у прежнего узла — своя: данные узла некуда переносить. */
    BothDatabases,

    /** Данные прежнего узла не ложатся в кассу без потерь: база повреждена, другой версии или не сошлась. */
    NodeDataUnfit,

    /** Касса не открыла свой каталог данных. */
    KassaNotOpened
}

/**
 * Касса не открылась: причина и то, что о ней знает журнал.
 *
 * @property detail сведения для обслуживания — техническим языком,
 *   без токенов, пинов и содержимого документов.
 */
data class StartProblem(val refusal: StartRefusal, val detail: String)
