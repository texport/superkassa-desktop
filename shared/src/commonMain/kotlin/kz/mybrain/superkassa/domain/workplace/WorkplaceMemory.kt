package kz.mybrain.superkassa.domain.workplace

/**
 * Что рабочее место помнит между запусками о кассах.
 *
 * Порт, а не файл: на настольной кассе память лежит файлами в каталоге
 * данных, на Android — в хранилище приложения. Экраны спрашивают
 * рабочее место, а не его устройство.
 *
 * Пина здесь нет и быть не может: он живёт только в памяти.
 */
interface WorkplaceMemory {

    /** Касса, за которой работали в прошлый раз; `null` — ещё ни за какой. */
    var rememberedKkmId: String?

    /**
     * Своё название кассы на этом рабочем месте; `null` — не давали.
     *
     * Название рабочего места сильнее названия владельца: его дали
     * позже и зная про то.
     */
    fun localName(kkmId: String): String?
}
