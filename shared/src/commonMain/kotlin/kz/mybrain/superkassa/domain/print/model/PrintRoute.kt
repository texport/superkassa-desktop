package kz.mybrain.superkassa.domain.print.model

/**
 * Как эта машина печатает печатную форму.
 *
 * Настольная касса видит принтеры системы по имени, и принтер выбирается
 * у кассы один раз. На Android принтера по имени нет: печать идёт
 * системным диалогом, в котором выбирают принтер, копии и «Сохранить как
 * PDF», а форма уходит в него документом PDF.
 */
enum class PrintRoute {
    /** Принтеры машины по имени: лента картинкой уходит на принтер кассы. */
    Printers,

    /** Системный диалог печати: принтер и копии выбирают в нём, форма уходит PDF. */
    SystemDialog;

    /** В каком виде форма уходит на печать. */
    val kind: PrintKind get() = if (this == SystemDialog) PrintKind.Pdf else PrintKind.Png
}
