package kz.mybrain.superkassa.domain.journal

/**
 * Журнал приложения: по нему обслуживание восстанавливает, что было.
 *
 * Записи — по-английски и без того, что даёт права или раскрывает
 * покупателя: пинов, токенов, фискальных документов и личных данных
 * здесь не бывает. Экран пишет, что сделал и чем кончилось, — касса,
 * смена, код отказа.
 */
interface Journal {

    /** Что сделано: вход, смена, выбор кассы. */
    fun info(text: String)

    /** Касса отказала по существу. */
    fun warn(text: String)

    /** Касса не смогла ответить. */
    fun failure(text: String)
}
