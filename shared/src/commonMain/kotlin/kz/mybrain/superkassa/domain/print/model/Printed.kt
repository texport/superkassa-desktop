package kz.mybrain.superkassa.domain.print.model

/** Чем кончилось задание печати у этой машины. */
enum class Printed {
    /** Задание ушло на принтер. */
    Sent,

    /** Принтер или система задания не приняли. */
    Refused,

    /** Кассир закрыл системный диалог печати: он передумал, говорить не о чем. */
    Cancelled
}
