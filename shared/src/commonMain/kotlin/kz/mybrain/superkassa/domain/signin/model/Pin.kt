package kz.mybrain.superkassa.domain.signin.model

/**
 * Каким бывает пин кассира.
 *
 * Те же пределы, что проверяет касса: проверка на месте нужна не вместо
 * неё, а чтобы кассир увидел причину до того, как нажмёт кнопку.
 */
object Pin {

    /** Короче четырёх цифр пин подобрать слишком легко. */
    const val MIN = 4

    /** Длиннее десяти касса не принимает: пин кассира и пин администратора новой кассы — от 4 до 10 цифр. */
    const val MAX = 10

    /** Пин набирается цифрами и не длиннее допустимого: лишнее не вводится. */
    fun digitsOf(text: String): String = text.filter(Char::isDigit).take(MAX)

    /**
     * Таким пином можно попробовать войти.
     *
     * Годен ли пин на деле, решает касса: приложение не пускает к ней
     * только заведомо неполный или лишний набор.
     */
    fun enterable(pin: String): Boolean = pin.length in MIN..MAX
}
