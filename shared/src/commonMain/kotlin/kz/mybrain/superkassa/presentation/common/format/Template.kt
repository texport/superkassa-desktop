package kz.mybrain.superkassa.presentation.common.format

/**
 * Подстановка в шаблон надписи: `%s` по порядку, `%2$s` — по номеру.
 *
 * Надписи на трёх языках держат место для числа или имени знаком `%s`,
 * а порядок слов у языков разный: «Внести %s?» и «%s салынсын ба?». Где
 * значения меняются местами — «показано 50 из 200» и «200 ішінен 50
 * көрсетілді», — место называется номером значения: `%2$s ішінен %1$s`.
 * Прежде номерное место не заполнялось вовсе, и на экране стояло
 * «Осталось %1$s». Разбор шаблона свой, без форматирования платформы:
 * общий код собирается и для Android, и для iOS.
 *
 * Значений меньше, чем мест, — лишние места остаются как есть: недостающее
 * слово видно на экране и в проверке, а не роняет экран кассира.
 */
fun String.fill(vararg values: Any): String {
    var next = 0
    return HOLE.replace(this) { hole ->
        val at = hole.groupValues[1].toIntOrNull()?.minus(1) ?: next++
        values.getOrNull(at)?.toString() ?: hole.value
    }
}

/** Место для значения в шаблоне надписи: `%s` или `%номер$s`. */
private val HOLE = Regex("""%(?:(\d+)\$)?s""")
