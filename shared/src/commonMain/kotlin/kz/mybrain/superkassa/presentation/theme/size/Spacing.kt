package kz.mybrain.superkassa.presentation.theme.size

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Отступы кассы.
 *
 * Шкала одна на всё приложение, имена — по смыслу места, а не по числу:
 * экраны собираются из этих значений и ничего своего не придумывают. Разъехавшиеся на пару точек поля видны
 * кассиру сразу, а найти причину в двадцати файлах с числами — нельзя.
 */
object Spacing {
    /**
     * Шаг шкалы — сетка Material 3 в четыре точки.
     *
     * Единственное число оформления, записанное точками: отступы ниже,
     * размеры полей, колонок, значков и окон ([Sizes] и экранные наборы
     * рядом) — кратные ему. Своих чисел экраны не заводят.
     */
    val step = 4.dp

    /**
     * Четверть шага — для обводок, линий и теней тоньше шага сетки:
     * ось графика в точку, обводка метки в две.
     */
    val fine = step / FINE_PER_STEP

    /** Внутри строки: значок и подпись, строки одного блока. */
    val inline = 1.steps

    /** Соседние элементы группы или списка друг под другом; поле ячейки таблицы. */
    val itemGap = 2.steps

    /** Кнопки и плашки в ряд — по Material 3 восемь точек. */
    val buttonGap = 2.steps

    /** Поле от поля формы; заголовок карточки от её содержимого. */
    val fieldGap = 3.steps

    /** Внутреннее поле карточки — по Material 3 шестнадцать точек. */
    val cardPadding = 4.steps

    /** Карточка от карточки, блок от блока в колонке. */
    val cardGap = 4.steps

    /** Поле справа под полосу прокрутки: полоса не ложится на содержимое. */
    val scrollbarGutter = 4.steps

    /** Панель от панели рядом — разделитель панелей Material 3. */
    val paneGap = 6.steps

    /** Группа карточек от группы, крупные блоки экрана. */
    val sectionGap = 6.steps

    /** Поле одиночного крупного блока: вход, пустое состояние, форма денег. */
    val blockPadding = 6.steps

    /**
     * Поле окна — по Material 3: шестнадцать точек на телефоне, двадцать
     * четыре шире. Ставит его каркас окна один раз вокруг раздела, а не
     * каждый экран сам.
     *
     * @param compact окно компактного класса — телефон стоймя.
     */
    fun windowMargin(compact: Boolean): Dp = if (compact) 4.steps else 6.steps
}

/**
 * Столько шагов шкалы: размер оформления, записанный кратным шагу.
 *
 * `60.steps` — двести сорок точек; экранные наборы размеров пишут так,
 * а не числом в точках, и на другой шаг шкала переходит правкой одного
 * [Spacing.step].
 */
val Int.steps: Dp get() = Spacing.step * this

/** Столько четвертей шага — для обводок и линий тоньше шага: `2.fine`. */
val Int.fine: Dp get() = Spacing.fine * this

/** Сколько тонких делений в шаге шкалы. */
private const val FINE_PER_STEP = 4
