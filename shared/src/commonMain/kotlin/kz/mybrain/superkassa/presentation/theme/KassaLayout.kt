package kz.mybrain.superkassa.presentation.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Размеры кассовых экранов: продажи, возврата, денег, входа и главного.
 *
 * Здесь только то, чего нет в общих токенах: пределы, после которых
 * часть строки уходит вниз, и рост главной кнопки. Доли колонок и ширины
 * столбцов берутся из [Panes] и [TableColumns].
 */
object KassaLayout {

    /**
     * Главная кнопка экрана: «Пробить чек», «Вернуть покупателю»,
     * «Внести», «Войти», «Закрыть смену».
     *
     * Одного роста с полем ввода рядом: у одной роли были кнопки
     * от 40 до 56 точек, и ниже 48 — меньше цели нажатия по Material 3.
     */
    val mainAction: Dp = Sizes.fieldHeight

    /**
     * Состав строки чека — количество, цена, ставка — не уже этого.
     *
     * Уже него сумма строки и её действия уходят на следующую строку:
     * прежде они стояли справа всегда и оставляли наименованию одну букву.
     */
    val positionDetail: Dp = 200.dp

    /**
     * Поле суммы одной оплаты не уже этого: в него помещается сумма
     * в сотни миллиардов тенге с тиынами основной ступенью.
     */
    val paymentAmount: Dp = 220.dp

    /**
     * Поле под полосой прокрутки кассы.
     *
     * Прибитые к низу итог и кнопка отступают от правого края на столько же,
     * сколько прокручиваемая часть над ними: иначе правые края колонки
     * стояли вразнобой.
     */
    val tillGutter: Dp = Spacing.normal

    /**
     * Плитка остатка ящика не уже этого: в неё помещается остаток
     * в миллиарды тенге малой ступенью главного числа на крупнейшем шрифте.
     */
    val drawerTile: Dp = 380.dp

    /** Во сколько раз плитка остатка шире соседних: в ней главное число экрана. */
    const val DRAWER_TILE_WEIGHT = 2f

    /**
     * Соседние плитки главного экрана не уже этого. Уже — плитки
     * переносятся.
     *
     * Ровно доля плитки остатка: ряд делится по долям, и при меньшей
     * наименьшей ширине соседей ряд вставал в строку, а плитке остатка
     * по доле доставалось меньше её наименьшей ширины — сумма срезалась.
     */
    val statTile: Dp = drawerTile / DRAWER_TILE_WEIGHT

    /**
     * Отклонённые БФД и документы смены на главном экране.
     *
     * Рядом, пока обоим хватает места: тридцать отказов над списком
     * вытесняли документы смены за нижний край. На тесном месте отказы
     * стоят над списком, как и прежде, но список берёт свою долю высоты
     * первым. Списку смены нужно больше, чем списку вообще: справа в его
     * строке стоят сумма и две кнопки, и уже этого названию документа
     * не остаётся места.
     */
    val refusedAndDocuments = PaneSplit(
        firstShare = 0.4f,
        firstMin = 320.dp,
        secondMin = 560.dp
    )
}
