package kz.mybrain.superkassa.presentation.theme.size

import androidx.compose.ui.unit.Dp

/**
 * Пределы ширины содержимого.
 *
 * Окно растягивают до широкого монитора, а строка текста и поле ввода
 * от этого удобнее не становятся: на 2560 точках сумма уезжала от названия
 * товара на 1700 точек, а поле «Регион» вытягивалось на 2050. Содержимое
 * растёт до предела и дальше стоит на месте, а лишний простор остаётся
 * полями окна.
 */
object ContentWidths {

    /**
     * Текст: абзац, длинное объяснение. Формы и карточки этим пределом
     * не ограничиваются — они занимают всю ширину раздела.
     *
     * Около семидесяти знаков основного шрифта — предел строки, которую
     * читают, не теряя начала следующей.
     */
    val reading = 160.steps

    /**
     * Рабочий экран целиком: чек с кассой, журнал, кабинет, аналитика.
     *
     * Упирается в него только большое и очень большое окно; до этого
     * рабочий экран занимает всё, что оставил рельс.
     */
    val workspace = 360.steps

    /**
     * Шапка отдаёт названию кассы не меньше этого.
     *
     * Кассир узнаёт свою кассу по имени; действия, которым не хватает
     * места, уходят в меню, а не отнимают у названия последние буквы.
     */
    val topBarTitle = 60.steps
}

/**
 * Доли двух панелей рядом.
 *
 * @param firstShare доля первой панели, когда места хватает обеим.
 * @param firstMin уже этого первая панель не бывает: иначе панели встают
 *   одна над другой или сменяют друг друга.
 * @param secondMin то же для второй панели.
 * @param secondMax шире этого вторая панель не растёт — лишнее отходит
 *   первой. `Dp.Infinity` — предела нет.
 */
data class PaneSplit(
    val firstShare: Float,
    val firstMin: Dp,
    val secondMin: Dp,
    val secondMax: Dp = Dp.Infinity
)

/**
 * Раскладки из двух панелей, общие для разделов.
 *
 * Одна и та же пара — список и подробности — встречается в журнале,
 * кабинете и возврате; доли у неё должны быть одними, иначе колонки
 * при переходе между разделами прыгают.
 */
object Panes {

    /** Зазор между панелями: тот же, что между блоками экрана. */
    val gap = Spacing.paneGap

    /**
     * Сколько высоты при раскладке одна над другой отдаётся второй панели
     * в самом большом случае; остальное остаётся первой.
     */
    const val STACKED_SECOND_SHARE = 0.6f

    /** Список слева, подробности выбранного справа: журнал, возврат, очередь. */
    val listDetail = PaneSplit(firstShare = 0.4f, firstMin = 80.steps, secondMin = 100.steps)

    /**
     * Чек слева, касса справа: итог, оплата и «Пробить чек».
     *
     * Касса не растёт на широком окне — её поля по смыслу постоянной
     * ширины, а простор нужен названиям товаров в чеке.
     */
    val receiptAndTill = PaneSplit(
        firstShare = 0.62f,
        firstMin = 90.steps,
        secondMin = 80.steps,
        secondMax = 110.steps
    )

    /** Дерево точек и касс слева, карточка выбранного справа: кабинет. */
    val placesAndCard = PaneSplit(firstShare = 0.34f, firstMin = 75.steps, secondMin = 105.steps)

    /** Карта и сведения о выбранном месте: аналитика. */
    val mapAndDetails = PaneSplit(
        firstShare = 0.62f,
        firstMin = 105.steps,
        secondMin = 80.steps,
        secondMax = 120.steps
    )
}
