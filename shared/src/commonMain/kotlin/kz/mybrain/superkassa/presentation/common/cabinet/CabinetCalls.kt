package kz.mybrain.superkassa.presentation.common.cabinet

/**
 * Обращения мастера к кабинету — с занятостью и словами кабинета окна.
 *
 * Отказ кабинета, истёкший доступ и отказ подписи владелец видит одними
 * словами и в мастере, и в разделах кабинета: мастер не разбирает помехи
 * кабинета сам, а отдаёт обращение тому, кто их уже разбирает. Пока
 * обращение идёт, кнопки кабинета окна заняты — и кнопки мастера тоже.
 */
interface CabinetCalls {

    /**
     * Обращение, которого ждёт владелец.
     *
     * @param action что делалось, по-английски: для журнала.
     * @return значение; `null` — не удалось, и помеха уже показана.
     */
    suspend fun <T> run(action: String, block: suspend () -> T): T?
}
