package kz.mybrain.superkassa.presentation.theme.size

import androidx.compose.ui.unit.dp

/**
 * Карточки и формы столбцами.
 *
 * Форма и карточка занимают всю ширину, которую им дал раздел: колонка
 * шириной чтения на широком окне оставляла правую половину экрана пустой,
 * и владелец принимал это за поломку. Чтобы карточка настроек не вытягивалась
 * на полторы тысячи точек, на широком окне карточки встают рядом.
 */
object CardGrid {

    /** Зазор между столбцами и между карточками в столбце: тот же, что между блоками экрана. */
    val gap = Spacing.normal

    /**
     * Уже этого столбец не бывает: в нём должно помещаться поле формы
     * с подписью и кнопка рядом. Узкая панель получает меньше столбцов,
     * чем позволил бы класс окна.
     */
    val columnMin = 440.dp

    /** Столбцов у компактного и среднего окна: телефон, планшет стоймя. */
    const val NARROW_COLUMNS: Int = 1

    /** Столбцов у расширенного и большого окна: планшет лёжа, ноутбук, монитор. */
    const val WIDE_COLUMNS: Int = 2

    /** Столбцов у очень большого окна: широкий и внешний монитор. */
    const val WIDEST_COLUMNS: Int = 3
}
