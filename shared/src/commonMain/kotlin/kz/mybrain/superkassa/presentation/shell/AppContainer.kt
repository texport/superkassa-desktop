package kz.mybrain.superkassa.presentation.shell

import kz.mybrain.superkassa.presentation.common.model.WindowServices

/**
 * Всё, что экранам нужно снаружи: порты `domain`, собранные из `data`.
 *
 * Собирается один раз — в точке сборки платформенного приложения, `Assembly.kt`
 * настольной кассы и `SuperkassaApp` Android, — и отдаётся каркасу окна.
 * Области контейнер не получают: каркас отдаёт фабрике модели области
 * общие службы окна и её собственный набор портов, фабрика собирает из них
 * сценарии, а модели достаются только сценарии и разговор с кассиром.
 * Так ни модель, ни область не видят чужих портов.
 *
 * Общие службы лежат в [services], порты областей — в [areas], по набору
 * на область. Область, которой понадобился новый порт, дописывает его
 * в свой набор, а не сюда: контейнер не растёт с каждой областью, а правки
 * областей не пересекаются.
 *
 * @property services касса, вход, память и вид рабочего места, разговор с кассиром.
 * @property areas порты областей — по набору на область.
 */
class AppContainer(val services: WindowServices, val areas: AreaPorts)
